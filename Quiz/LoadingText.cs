    public QuizManager QuizManager;

    // один список вместо шести: каждый элемент содержит вопрос, четыре неверных ответа и правильный ответ
    public List<Question> AllQuestions = new List<Question>();

    void Start()
    {
        QuizManager = gameObject.GetComponent<QuizManager>();
    }

    // Публичный метод: синхронно наполняет список вопросами и ответами.
    // Вызывается напрямую из QuizManager.Start() — без Invoke и таймингов.
    public void LoadQuestions()
    {
        if (QuizManager == null)
            QuizManager = FindAnyObjectByType<QuizManager>();

        AllQuestions.Clear(); // очищаем список, чтобы при повторном запуске не было дубликатов

        switch (QuizManager.NameQuiz) // проверяем какой уровень выбрал игрок, и вызываем методы
        {
            case "Fairytales": // после того, как мы определились с тем, какой уровень выбрал игрок, вызываем методы получения вопросов и ответов
                QuestionsFairyTales();
                break;
            case "Countries":
                QuestionsCountries();
                break;
            case "History":
                QuestionsHistory();
                break;
        }
    }

    // Хелпер, чтобы методы с вопросами оставались читаемыми:
    // один вызов AddQuestion = один вопрос со всеми вариантами ответа
    private void AddQuestion(string text, string wrong1, string wrong2, string wrong3, string wrong4, string correct)
    {
        Question q = new Question();
        q.Text = text;
        q.WrongAnswers = new string[] { wrong1, wrong2, wrong3, wrong4 };
        q.CorrectAnswer = correct;
        AllQuestions.Add(q);
    }

